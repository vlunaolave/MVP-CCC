import type { CompanySeed } from "./types";

type CompanyBase = Omit<CompanySeed, "sector" | "fuenteDatos">;
type Sector = CompanySeed["sector"];

const CAMARA = "Cámara de Comercio de Cali";
const DEPTO = "Valle del Cauca";

function empresa(
  input: Pick<
    CompanyBase,
    | "id"
    | "nit"
    | "razonSocial"
    | "nombreComercial"
    | "actividadEconomicaCodigo"
    | "actividadEconomicaDescripcion"
    | "tamanoEmpresa"
    | "numeroEmpleados"
    | "municipio"
    | "direccion"
    | "fechaConstitucion"
    | "representanteLegal"
    | "capital"
    | "activos"
  > & { tipoOrganizacion?: string; fechaMatricula?: string },
): CompanyBase {
  const constitucion = input.fechaConstitucion ?? "2019-04-01";
  return {
    id: input.id,
    nit: input.nit,
    razonSocial: input.razonSocial,
    nombreComercial: input.nombreComercial,
    tipoOrganizacion: input.tipoOrganizacion ?? "S.A.S.",
    tipoRegistro: "MERCANTIL",
    estadoMatricula: "ACTIVA",
    numeroMatricula: `${input.nit.replace("-", "").slice(-6)}-1`,
    fechaMatricula: input.fechaMatricula ?? constitucion,
    fechaRenovacion: "2026-02-12",
    camaraComercio: CAMARA,
    municipio: input.municipio,
    departamento: DEPTO,
    direccion: input.direccion,
    telefono: null,
    email: null,
    sitioWeb: null,
    actividadEconomicaCodigo: input.actividadEconomicaCodigo,
    actividadEconomicaDescripcion: input.actividadEconomicaDescripcion,
    tamanoEmpresa: input.tamanoEmpresa,
    numeroEmpleados: input.numeroEmpleados,
    capital: input.capital,
    activos: input.activos,
    fechaConstitucion: constitucion,
    estado: "VIGENTE",
    representanteLegal: input.representanteLegal,
  };
}

